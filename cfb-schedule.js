function cfbPrices(home, away, rivalry) {
  const hp   = CFB_MARKET[home] || 1.0;
  const ap   = CFB_MARKET[away] || 0.85;
  const rv   = rivalry ? 1.18 : 1.0;
  const base = Math.round(98 * (hp * 0.65 + ap * 0.35) * rv);
  const sh   = Math.round(base * 0.94);
  const sg   = Math.round(base * 0.88);
  return [
    { platform: 'Ticketmaster', base,  fees: Math.round(base * 0.18) },
    { platform: 'StubHub',      base: sh, fees: Math.round(sh  * 0.15) },
    { platform: 'SeatGeek',     base: sg, fees: Math.round(sg  * 0.14) },
  ];
}

