function isRivalry(home, away) {
  return NBA_RIVALRIES.some(([a, b]) =>
    (a === home && b === away) || (b === home && a === away));
}

function nbaPrices(home, away) {
  const hp  = NBA_MARKET[home]  || 1.0;
  const ap  = NBA_MARKET[away]  || 1.0;
  const riv = isRivalry(home, away) ? 1.22 : 1.0;
  const base = Math.round(110 * (hp * 0.6 + ap * 0.4) * riv);
  const sh   = Math.round(base * 0.94);
  const sg   = Math.round(base * 0.88);
  return [
    { platform: 'Ticketmaster', base, fees: Math.round(base * 0.17) },
    { platform: 'StubHub',      base: sh, fees: Math.round(sh * 0.15) },
    { platform: 'SeatGeek',     base: sg, fees: Math.round(sg * 0.13) },
  ];
}

